"""
Notification and Alert Dispatcher for CloudPulse.
Dispatches incident alerts via Amazon SNS or local notification inbox.
"""

from abc import ABC, abstractmethod
import os
import time
import json
import boto3
from typing import Optional, Dict, Any, List
try:
    from ..core.models import Incident, Monitor
except (ImportError, ValueError):
    from core.models import Incident, Monitor


class Notifier(ABC):
    @abstractmethod
    def send_incident_alert(self, incident: Incident, monitor: Monitor, event_type: str) -> bool:
        pass


class SNSNotifier(Notifier):
    """
    Amazon Simple Notification Service (SNS) Notifier.
    Publishes formatted alert notifications to an SNS Topic ARN.
    """
    def __init__(self, topic_arn: Optional[str] = None):
        self.topic_arn = topic_arn or os.environ.get("SNS_TOPIC_ARN", "")
        region = os.environ.get("AWS_REGION", os.environ.get("AWS_DEFAULT_REGION", "us-east-1"))
        self.sns_client = boto3.client("sns", region_name=region)

    def send_incident_alert(self, incident: Incident, monitor: Monitor, event_type: str) -> bool:
        if not self.topic_arn:
            raise ValueError("SNS_TOPIC_ARN is not configured in environment variables.")

        is_resolved = (event_type == "INCIDENT_RESOLVED" or incident.status == "RESOLVED")
        subject = f"[CloudPulse Alert] {'RESOLVED' if is_resolved else 'INCIDENT OPEN'}: {monitor.name}"
        
        duration_text = f"Downtime Duration: {incident.duration_seconds} seconds\n" if is_resolved else ""

        message_body = (
            f"==================================================\n"
            f"CLOUDPULSE ALERT NOTIFICATION\n"
            f"==================================================\n"
            f"Event: {event_type}\n"
            f"Status: {incident.status}\n"
            f"Monitor: {monitor.name}\n"
            f"Target URL: {monitor.url}\n"
            f"Timestamp: {incident.started_at}\n"
            f"Failure Cause: {incident.cause}\n"
            f"Consecutive Failures: {incident.consecutive_failures}\n"
            f"Last Status Code: {incident.last_status_code}\n"
            f"{duration_text}"
            f"Recipient: {monitor.alert_email or 'Default SNS Subscriber'}\n"
            f"==================================================\n"
            f"Automated notification generated by CloudPulse Serverless Platform.\n"
        )

        response = self.sns_client.publish(
            TopicArn=self.topic_arn,
            Subject=subject[:100],  # SNS subjects max 100 chars
            Message=message_body,
            MessageAttributes={
                "MonitorId": {"DataType": "String", "StringValue": monitor.id},
                "EventType": {"DataType": "String", "StringValue": event_type},
                "Status": {"DataType": "String", "StringValue": incident.status}
            }
        )
        return bool(response.get("MessageId"))


class LocalNotifier(Notifier):
    """
    Local simulation notifier for development without AWS credentials.
    Captures sent notifications in memory/list to display on UI and inspect in tests.
    """
    notifications: List[Dict[str, Any]] = []

    def send_incident_alert(self, incident: Incident, monitor: Monitor, event_type: str) -> bool:
        is_resolved = (event_type == "INCIDENT_RESOLVED" or incident.status == "RESOLVED")
        subject = f"[CloudPulse Alert] {'RESOLVED' if is_resolved else 'INCIDENT OPEN'}: {monitor.name}"
        
        notification = {
            "id": f"notif_{int(time.time()*1000)}_{len(self.notifications) + 1}",
            "subject": subject,
            "monitor_id": monitor.id,
            "monitor_name": monitor.name,
            "monitor_url": monitor.url,
            "status": incident.status,
            "event_type": event_type,
            "cause": incident.cause,
            "recipient": monitor.alert_email or "admin@cloudpulse.local",
            "timestamp": incident.started_at,
            "duration_seconds": incident.duration_seconds
        }
        self.notifications.insert(0, notification)
        try:
            from ..storage import get_storage
            storage = get_storage()
            if hasattr(storage, "save_notification"):
                storage.save_notification(notification)
        except Exception:
            pass
        return True

    @classmethod
    def get_notifications(cls) -> List[Dict[str, Any]]:
        try:
            from ..storage import get_storage
            storage = get_storage()
            if hasattr(storage, "get_notifications"):
                db_notifs = storage.get_notifications()
                if db_notifs:
                    return db_notifs
        except Exception:
            pass
        return cls.notifications

    @classmethod
    def clear(cls):
        cls.notifications.clear()


_notifier_instance = None


def get_notifier() -> Notifier:
    global _notifier_instance
    if _notifier_instance is not None:
        return _notifier_instance

    backend = os.environ.get("NOTIFICATION_BACKEND", "").lower()
    is_aws = bool(os.environ.get("AWS_LAMBDA_FUNCTION_NAME") or os.environ.get("AWS_EXECUTION_ENV"))
    force_local = os.environ.get("USE_LOCAL_STORAGE", "auto").lower() in ("true", "1", "yes")

    if (backend == "sns" or is_aws) and not force_local:
        _notifier_instance = SNSNotifier()
    else:
        _notifier_instance = LocalNotifier()

    return _notifier_instance
